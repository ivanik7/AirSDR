#!/usr/bin/env python3
# Generates lib/ui/colormaps.g.dart from SDR++ root/res/colormaps/*.json
# (SDR++ core/src/gui/colormaps.cpp loads the same files at runtime).
# Usage: python3 tool/ui/gen_colormaps.py ~/prj/sdrpp/root/res/colormaps lib/ui/colormaps.g.dart
import json
import os
import sys

src, dst = sys.argv[1], sys.argv[2]
maps = []
for fn in sorted(os.listdir(src)):
    if not fn.endswith('.json'):
        continue
    with open(os.path.join(src, fn)) as f:
        d = json.load(f)
    cols = []
    for c in d['map']:
        c = c.lstrip('#')
        cols.append(int(c, 16))
    maps.append((fn[:-5], d['name'], d.get('author', ''), cols))

out = []
out.append('// GENERATED by tool/ui/gen_colormaps.py from SDR++ root/res/colormaps/*.json')
out.append('// (SDR++ @8c9f5ee, GPL-3.0). Do not edit by hand.')
out.append('// Colors are 0xRRGGBB exactly as in the JSON "map" arrays.')
out.append('')
out.append("part of 'colormaps.dart';")
out.append('')
out.append('const List<ColorMapDef> sdrppColorMaps = <ColorMapDef>[')
for key, name, author, cols in maps:
    out.append('  ColorMapDef(')
    out.append(f"    id: '{key}',")
    out.append(f"    name: '{name}',")
    out.append(f"    author: {json.dumps(author)},")
    out.append('    colors: <int>[')
    for i in range(0, len(cols), 6):
        out.append('      ' + ', '.join('0x%06X' % c for c in cols[i:i + 6]) + ',')
    out.append('    ],')
    out.append('  ),')
out.append('];')
out.append('')
with open(dst, 'w') as f:
    f.write('\n'.join(out))
print(f'{len(maps)} colormaps -> {dst}')
